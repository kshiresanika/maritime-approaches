def project(tracks: list[AisTrack], pose: ScenePose) -> dict[str, Any]:
    """Bearing, range and visibility for every vessel. No noise yet."""
    lat = np.array([t.claimed_lat_deg for t in tracks])
    lon = np.array([t.claimed_lon_deg for t in tracks])
    bearing, rng = predict_measurement(
        camera_lat_deg=pose.lat_deg, camera_lon_deg=pose.lon_deg,
        target_lat_deg=lat, target_lon_deg=lon,
    )
    visible = is_in_field_of_view(
        bearing, rng,
        boresight_deg_true=pose.boresight_deg_true,
        fov_half_angle_deg=pose.fov_half_angle_deg,
        max_range_m=pose.max_range_m,
    )
    return {"bearing": bearing, "range": rng, "visible": np.asarray(visible, dtype=bool)}


def _synthetic_detection_confidence(apparent_width_px: float, rng) -> float:
    """A plausible detector confidence for a synthetic contact.

    ONE RULE FOR REAL VESSELS AND FOR CLUTTER, deliberately. It would be easy to give
    injected clutter a systematically low confidence and real vessels a high one, and
    that would be cheating: any downstream use of detection_confidence would then
    separate the two trivially, and the false-positive rate measured on this scene
    would be optimistic in a way nothing in the output reveals.

    Instead confidence rises with APPARENT PIXEL WIDTH, which is the physical reason a
    real detector is more certain about a near contact than a far one. Clutter is small,
    so it lands low WITHOUT being labelled low, and a genuinely distant vessel lands in
    the same band as clutter -- which is exactly the ambiguity the pipeline has to earn
    its way out of.

    Saturating rather than linear: past a few hundred pixels a detector is as sure as it
    is going to get. Measured shape: 6 px -> 0.43, 22 px -> 0.58, 40 px -> 0.70,
    100 px -> 0.85, 200 px -> 0.90.
    """
    import math as _math
    base = 0.35 + 0.55 * (1.0 - _math.exp(-max(0.0, apparent_width_px) / 40.0))
    return float(min(0.98, max(0.25, base + rng.normal(0.0, 0.05))))


def make_contact(
    *, track: AisTrack, bearing_true: float, range_m: float, pose: ScenePose,
    scene_time: datetime, rng: np.random.Generator, noise: NoiseModel,
    contact_id: str, track_length_frames: int,
) -> EoContact:
    """
    Build one EoContact from one vessel's truth state, with measurement error applied.

    Note the ordering, which matters: geometry is perturbed FIRST, then the pixel box is
    computed from the perturbed bearing. Doing it the other way round -- perfect box,
    noisy bearing -- would produce a contact whose bbox and bearing disagree, and any
    downstream code that recomputes bearing from the box (a reasonable thing to do)
    would silently get a different answer than the one in the field.
    """
    # 1. Bearing error. Two independent sources, so they add in quadrature.
    #    Pose yaw error is SYSTEMATIC -- it rotates the whole scene by one amount -- but
    #    it is applied per-contact here for simplicity; the run manifest records that.
    b_sigma = math.sqrt(pose.yaw_uncertainty_deg ** 2 + noise.bearing_centroid_sigma_deg ** 2)
    obs_bearing = wrap_360(bearing_true + rng.normal(0.0, b_sigma))

    # 2. Range error is FRACTIONAL, not absolute. A monocular range estimate at 5 km is
    #    not 5000 +/- 200 m, it is 5000 +/- 1250 m, because the estimate divides by an
    #    apparent size that is itself only a few pixels. Modelling it as absolute error
    #    would make distant contacts look far more trustworthy than they are, and
    #    distant contacts are exactly the ones a patrol decision turns on.
    r_sigma = range_m * noise.range_fraction_sigma
    obs_range = max(1.0, range_m + rng.normal(0.0, r_sigma)) if r_sigma > 0 else range_m

    # 3. Pixel geometry, derived from the PERTURBED bearing.
    rel = shortest_arc_deg(obs_bearing, pose.boresight_deg_true)
    centre_x = pixel_column_for_relative_bearing(rel, pose.image_width_px, pose.hfov_deg)
    f_px = focal_length_px(pose.image_width_px, pose.hfov_deg)

    true_len = track.claimed_length_m or 30.0
    width_px = max(4.0, f_px * true_len / max(range_m, 1.0))
    height_px = max(3.0, width_px / 3.2)
    x0 = int(round(centre_x - width_px / 2.0))
    x1 = int(round(centre_x + width_px / 2.0))
    y_c = pose.image_height_px * 0.55
    y0 = int(round(y_c - height_px / 2.0))
    y1 = int(round(y_c + height_px / 2.0))
    x0, x1 = max(0, x0), min(pose.image_width_px, max(x0 + 1, x1))
    y0, y1 = max(0, y0), min(pose.image_height_px, max(y0 + 1, y1))

    b_unc = bearing_uncertainty_deg(
        float(x1 - x0), float(centre_x), pose.image_width_px, pose.hfov_deg,
        pose.yaw_uncertainty_deg,
    )

    # 4. Observed length. Truth times a fractional error -- the same reasoning as range,
    #    and in fact the two are coupled in reality (length is derived FROM range).
    #    Kept independent here, which is a simplification recorded in the manifest.
    obs_len = None
    obs_len_unc = None
    if track.claimed_length_m is not None:
        scale = 1.0 + rng.normal(0.0, noise.length_fraction_sigma)
        obs_len = max(1.0, track.claimed_length_m * max(0.2, scale))
        obs_len_unc = max(1.0, obs_len * noise.length_fraction_sigma)

    # 5. Observed class, with CONFUSION RESTRICTED TO VISUALLY SIMILAR TYPES.
    obs_class = track.claimed_ship_type
    if obs_class == "unknown":
        # Lane A's conservative policy: "unknown" means a claim was made that has no
        # honest silhouette equivalent. The camera still sees SOMETHING, so the observed
        # class is not None -- but it must never be compared. That suppression is
        # consistency.py's job; here we just record what was seen.
        obs_class = None
    if obs_class is not None and rng.random() < noise.p_class_confusion:
        alts = CLASS_CONFUSION.get(obs_class, [])
        if alts:
            obs_class = str(rng.choice(alts))
    obs_class_conf = (
        float(rng.uniform(noise.class_confidence_lo, noise.class_confidence_hi))
        if obs_class is not None else None
    )

    # 6. Motion. Only meaningful with a multi-frame track -- a single-frame contact
    #    cannot support a speed or heading observation, and contracts.py has a
    #    defer_reason (single_frame_contact) that exists precisely for this.
    obs_heading = None
    obs_speed = None
    if track_length_frames > 1:
        base_hdg = track.claimed_heading_deg_true
        if base_hdg is None:
            base_hdg = track.claimed_cog_deg_true
        if base_hdg is not None:
            obs_heading = wrap_360(base_hdg + rng.normal(0.0, noise.heading_sigma_deg))
        if track.claimed_sog_kn is not None:
            ms = track.claimed_sog_kn * KN_TO_MS
            obs_speed = max(0.0, ms * (1.0 + rng.normal(0.0, noise.speed_fraction_sigma)))

    return EoContact(
        contact_id=contact_id,
        frame_time_utc=scene_time,
        frame_ref=f"synthetic://{pose.pose_ref}/{scene_time.isoformat()}",
        bbox_px=(x0, y0, x1, y1),
        observed_bearing_deg_true=obs_bearing,
        bearing_uncertainty_deg=b_unc,
        detection_confidence=_synthetic_detection_confidence(width_px, rng),
        observed_bearing_rel_deg=max(-180.0, min(180.0, rel)),
        observed_range_m=obs_range,
        range_uncertainty_m=max(1.0, r_sigma) if r_sigma > 0 else 1.0,
        observed_class=obs_class,
        observed_class_confidence=obs_class_conf,
        observed_length_m=obs_len,
        observed_length_uncertainty_m=obs_len_unc,
        observed_heading_deg_true=obs_heading,
        observed_speed_ms=obs_speed,
        track_length_frames=track_length_frames,
        camera_pose_ref=pose.pose_ref,
    )


def make_clutter_contact(
    *, pose: ScenePose, scene_time: datetime, rng: np.random.Generator,
    noise: NoiseModel, contact_id: str,
) -> EoContact:
    """
    A contact that corresponds to no vessel at all: a wave crest, a buoy, a wake, a
    channel marker misread by the detector as a hull.

    WHY THIS IS IN THE SCENE ON PURPOSE. Clutter is the dominant source of DARK false
    positives in any real deployment -- far more common than an actual dark vessel -- so
    a harness without it flatters the pipeline enormously. If the prioritizer cannot
    push clutter below a real anomaly, criterion 2 has not been met, and this is the only
    thing in the scene that tests that.
    """
    rel = float(rng.uniform(-pose.fov_half_angle_deg, pose.fov_half_angle_deg))
    bearing = wrap_360(pose.boresight_deg_true + rel)
    rng_m = float(rng.uniform(0.25, 1.0)) * pose.max_range_m
    centre_x = pixel_column_for_relative_bearing(rel, pose.image_width_px, pose.hfov_deg)
    w = float(rng.uniform(6.0, 22.0))
    h = max(3.0, w / 2.5)
    x0 = int(max(0, round(centre_x - w / 2)))
    x1 = int(min(pose.image_width_px, round(centre_x + w / 2)))
    y_c = pose.image_height_px * 0.56
    return EoContact(
        contact_id=contact_id,
        frame_time_utc=scene_time,
        frame_ref=f"synthetic://{pose.pose_ref}/{scene_time.isoformat()}",
        bbox_px=(x0, int(y_c - h / 2), max(x0 + 1, x1), int(y_c + h / 2)),
        observed_bearing_deg_true=bearing,
        bearing_uncertainty_deg=bearing_uncertainty_deg(
            float(max(1, x1 - x0)), float(centre_x), pose.image_width_px,
            pose.hfov_deg, pose.yaw_uncertainty_deg),
        detection_confidence=_synthetic_detection_confidence(w, rng),
        observed_bearing_rel_deg=rel,
        observed_range_m=rng_m,
        range_uncertainty_m=rng_m * noise.range_fraction_sigma or 1.0,
        observed_class=None,                 # the detector fired; the VLM could not say
        observed_class_confidence=None,
        observed_length_m=None,
        observed_length_uncertainty_m=None,
        track_length_frames=1,               # clutter does not persist -> defer signal
        camera_pose_ref=pose.pose_ref,
    )


# ============================================================================
# Mutation: turning truth into a lie.
# ============================================================================

def spoof_length(track: AisTrack, factor: float, *, keep_size_consistent: bool) -> AisTrack:
    """
    Rewrite the claimed length.

    THE SUBTLETY WORTH KNOWING: AIS declares dimensions TWICE -- once as Length/Width,
    and once as the reference-point offsets Size A/B/C/D, where A+B == length. A lazy
    spoofer changes only Length and leaves A+B contradicting it, which is detectable
    from the AIS message ALONE, without a camera at all. That is a real and cheap check
    and consistency.py should have it.

    keep_size_consistent=True generates the COMPETENT spoofer who updates both, and
    that one can only be caught by the camera. Default True, because building for the
    lazy adversary is how you get a demo that impresses nobody who knows the domain.
    """
    d = track.model_dump()
    old = d.get("claimed_length_m")
    if old is None:
        return track
    new = round(old * factor, 1)
    d["claimed_length_m"] = new
    if keep_size_consistent and d.get("claimed_size_a_m") is not None \
            and d.get("claimed_size_b_m") is not None:
        ratio = new / old if old else 1.0
        d["claimed_size_a_m"] = round(d["claimed_size_a_m"] * ratio, 1)
        d["claimed_size_b_m"] = round(d["claimed_size_b_m"] * ratio, 1)
    return AisTrack(**d)


def spoof_class(track: AisTrack, new_class: str) -> AisTrack:
    d = track.model_dump()
    d["claimed_ship_type"] = new_class
    return AisTrack(**d)


def spoof_position(track: AisTrack, offset_m: float, azimuth_deg: float) -> AisTrack:
    """
    Displace the CLAIM, leaving the hull where it is.

    This is the one spoof where the observation is untouched: the vessel is physically
    where it always was, and the camera sees it there. The lie is only in the broadcast.
    Downstream this shows up twice -- as an in-view claim with nothing at its position,
    and as an observation whose nearest claim is 800 m away -- which is why association
    reports BOTH an unmatched track and an unmatched contact, and why verdict.py has to
    be careful not to count one event as two findings.
    """
    d = track.model_dump()
    lon2, lat2, _ = GEOD.fwd(d["claimed_lon_deg"], d["claimed_lat_deg"],
                             azimuth_deg, offset_m)
    d["claimed_lat_deg"] = float(lat2)
    d["claimed_lon_deg"] = float(lon2)
    return AisTrack(**d)


def spoof_heading(track: AisTrack, delta_deg: float) -> AisTrack:
    d = track.model_dump()
    base = d.get("claimed_heading_deg_true")
    if base is None:
        base = d.get("claimed_cog_deg_true")
    if base is None:
        return track
    d["claimed_heading_deg_true"] = wrap_360(base + delta_deg)
    return AisTrack(**d)


