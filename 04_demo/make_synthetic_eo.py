def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Build a synthetic EO scene from real AIS. Indoor demo, D0.")
    p.add_argument("--ais", required=True, type=Path,
                   help="Pseudonymised golden-window CSV (*_anon.csv).")
    p.add_argument("--out", required=True, type=Path, help="Output directory.")
    p.add_argument("--scene-time", type=str, default=None,
                   help="ISO-8601 with offset. Default: midpoint of the AIS window.")
    p.add_argument("--window-s", type=float, default=120.0,
                   help="Half-width, seconds, for picking each vessel's truth state.")
    p.add_argument("--seed", type=int, default=20260830,
                   help="Recorded in the manifest. Same seed = same scene.")

    g = p.add_argument_group("camera pose")
    g.add_argument("--auto-pose", action="store_true", default=True,
                   help="Place the camera across the busiest lane. Default.")
    g.add_argument("--camera-lat", type=float)
    g.add_argument("--camera-lon", type=float)
    g.add_argument("--boresight", type=float, help="Degrees TRUE.")
    g.add_argument("--hfov", type=float, default=60.0)
    g.add_argument("--yaw-sigma", type=float, default=2.0,
                   help="1-sigma pose yaw error. 1.0 surveyed, 5.0 phone compass, "
                        "180.0 = deliberately worthless.")
    g.add_argument("--max-range", type=float, default=8000.0)
    g.add_argument("--image-width", type=int, default=1920)
    g.add_argument("--image-height", type=int, default=1080)

    f = p.add_argument_group("fault injection")
    for kind, default in (("dark", 2), ("length-spoof", 2), ("class-spoof", 1),
                          ("position-spoof", 1), ("heading-spoof", 1),
                          ("coverage-hole", 2), ("missed-detection", 1)):
        f.add_argument(f"--n-{kind}", type=int, default=default)
    f.add_argument("--lazy-spoofer", action="store_true",
                   help="Length spoof leaves Size A/B contradicting Length, which is "
                        "detectable from AIS alone. Default is the competent spoofer.")
    f.add_argument("--noise", choices=("normal", "none"), default="normal",
                   help="'none' is for debugging plumbing ONLY. A zero-noise scene "
                        "associates at zero sigma and proves nothing.")
    f.add_argument("--allow-real-identities", action="store_true",
                   help="Dangerous. Permits non-999 MMSIs. Output must never be shown.")
    p.add_argument("--dry-run", action="store_true",
                   help="Print the scene summary, write nothing.")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)

    if not args.ais.exists():
        raise SystemExit(
            f"AIS file not found: {args.ais}\n"
            "Run 02_data/make_golden_window.py first, and point --ais at the "
            "*_anon.csv it writes.")

    if args.scene_time:
        scene_time = datetime.fromisoformat(args.scene_time)
        if scene_time.tzinfo is None:
            raise SystemExit(
                "--scene-time has no UTC offset. Naive datetimes are refused here for "
                "the same reason contracts.py refuses them: the DMA CSV is dd/mm/yyyy "
                "and a silently-assumed timezone is how a two-hour error reaches a "
                "verdict.")
    else:
        scene_time = datetime(2026, 8, 25, 10, 30, tzinfo=timezone.utc)

    tracks, ais_stats = load_truth_states(args.ais, scene_time, args.window_s)
    if not tracks:
        raise SystemExit(
            f"No AIS reports within +/-{args.window_s:.0f}s of {scene_time.isoformat()}. "
            "Check --scene-time against the window in the file name.")
    assert_pseudonymised(tracks, allow_real=args.allow_real_identities)

    if args.camera_lat is not None and args.camera_lon is not None \
            and args.boresight is not None:
        pose = ScenePose(
            pose_ref="synthetic-manual", lat_deg=args.camera_lat,
            lon_deg=args.camera_lon, boresight_deg_true=wrap_360(args.boresight),
            hfov_deg=args.hfov, yaw_uncertainty_deg=args.yaw_sigma,
            max_range_m=args.max_range, image_width_px=args.image_width,
            image_height_px=args.image_height, height_m=25.0)
    else:
        pose = auto_pose(tracks, max_range_m=args.max_range, hfov_deg=args.hfov,
                         yaw_uncertainty_deg=args.yaw_sigma,
                         image_width_px=args.image_width,
                         image_height_px=args.image_height)

    noise = NoiseModel() if args.noise == "normal" else NoiseModel.off()
    rng = np.random.default_rng(args.seed)
    plan = {
        "dark": args.n_dark, "length_spoof": args.n_length_spoof,
        "class_spoof": args.n_class_spoof, "position_spoof": args.n_position_spoof,
        "heading_spoof": args.n_heading_spoof, "coverage_hole": args.n_coverage_hole,
        "missed_detection": args.n_missed_detection,
    }

    scene = build_scene(tracks=tracks, pose=pose, scene_time=scene_time, rng=rng,
                        noise=noise, plan=plan,
                        keep_size_consistent=not args.lazy_spoofer)

    manifest = {
        "harness_version": HARNESS_VERSION,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "seed": args.seed,
        "geometry_source": _GEOM_SOURCE,
        "ais": {"path": str(args.ais), **ais_stats},
        "pose": pose.to_dict(),
        "noise_model": {k: getattr(noise, k) for k in noise.__dataclass_fields__},
        "fault_plan": plan,
        "spoofer_competence": "lazy" if args.lazy_spoofer else "competent",
        "caveats": [
            "EO contacts are SYNTHETIC. No camera observed anything.",
            "AIS is real DMA traffic, pseudonymised to 999-prefixed MMSIs.",
            "Noise-model parameters are defensible estimates, NOT measurements.",
            "Pose yaw error is applied per-contact; in reality it is systematic "
            "across a run and rotates the whole scene together.",
            "Observed length and observed range are perturbed independently; in "
            "reality length is derived from range and the two errors are correlated.",
            "No sea clutter, weather, glare, occlusion by other hulls, or lens "
            "distortion is modelled beyond the clutter contacts listed above.",
        ],
    }

    print_summary(scene, pose, manifest)
    if args.dry_run:
        print("\n--dry-run: nothing written.")
        return 0

    write_scene(args.out, scene, manifest)
    print(f"\nwritten to {args.out}/")
    for f_ in ("ais_tracks.jsonl", "eo_contacts.jsonl", "ground_truth.jsonl",
               "scene_manifest.json", "READ_ME_FIRST.txt"):
        print(f"  {f_}")
    print("\nNothing in 03_src may import ground_truth.jsonl. It is the answer key.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
