# ============================================================================
# Geometry helpers.
#
# These duplicate two small functions from eo_detector.py. They are imported from
# there when it imports cleanly, and only re-implemented when it does not -- that
# module pulls in cv2 and ultralytics at import time, which are heavy and, on a
# machine without them, would make this harness unrunnable for no reason.
#
# The fallback formulas are byte-identical to lane B's. If lane B changes the
# bearing model, THIS FALLBACK IS A DIVERGENCE RISK -- it belongs in geometry.py,
# which is still empty. Filed to lane B.
# ============================================================================

# Lane B delivered geometry.py while this harness was being written, and it now owns
# the bearing model that eo_detector.py used to hold. Import from there.
#
# WHY THE FALLBACK STILL EXISTS: if geometry.py cannot be imported (a missing pyproj on
# a stripped machine), a SILENT fallback to a local copy is the dangerous outcome -- the
# harness would keep running and produce bearings from a second, possibly divergent,
# implementation. So the fallback announces itself, and _GEOM_SOURCE is written into the
# scene manifest so any run built on it is identifiable after the fact.

try:
    from geometry import (                                   # noqa: E402
        bearing_uncertainty_deg,
        focal_length_px,
        signed_delta_deg as _signed_delta_deg,
    )
    _GEOM_SOURCE = "geometry"
except Exception as _exc:  # pragma: no cover
    import warnings
    warnings.warn(
        f"geometry.py unavailable ({type(_exc).__name__}: {_exc}). Falling back to a "
        f"LOCAL copy of the bearing model. Bearings from this run come from a second "
        f"implementation and must not be compared against a run that used geometry.py.",
        stacklevel=2)
    _GEOM_SOURCE = "local_fallback"

    def focal_length_px(image_width_px: int, hfov_deg: float) -> float:
        return (image_width_px / 2.0) / math.tan(math.radians(hfov_deg) / 2.0)

    def bearing_uncertainty_deg(
        bbox_width_px: float,
        centre_x_px: float,
        image_width_px: int,
        hfov_deg: float,
        yaw_uncertainty_deg: float,
    ) -> float:
        f = focal_length_px(image_width_px, hfov_deg)
        centroid_px = max(bbox_width_px * 0.10, 1.0)
        d_deg_d_px = math.degrees(f / (f * f + (centre_x_px - image_width_px / 2.0) ** 2))
        return math.sqrt(yaw_uncertainty_deg ** 2 + (centroid_px * d_deg_d_px) ** 2)

    def _signed_delta_deg(a: float, b: float) -> float:
        return (a - b + 180.0) % 360.0 - 180.0


def pixel_column_for_relative_bearing(
    rel_deg: float, image_width_px: int, hfov_deg: float
) -> float:
    """
    Inverse of eo_detector.relative_bearing_deg.

    WHY THE INVERSE AND NOT A LINEAR MAP: lane B uses atan2 because a rectilinear lens
    does not put angle linearly onto pixels. If this harness placed boxes linearly, then
    every synthetic contact near a frame edge would carry a bearing several degrees away
    from where the real detector would have put it -- and several degrees is larger than
    the mismatches we are trying to detect. The synthetic frame has to obey the same
    optics as the real one or the demo is measuring the harness, not the pipeline.
    """
    f = focal_length_px(image_width_px, hfov_deg)
    return image_width_px / 2.0 + f * math.tan(math.radians(rel_deg))


def shortest_arc_deg(a: float, b: float) -> float:
    """Signed shortest angular difference a - b in (-180, +180]. Delegates to lane B."""
    return _signed_delta_deg(a, b)


def wrap_360(deg: float) -> float:
    return deg % 360.0


