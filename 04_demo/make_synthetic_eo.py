"""
make_synthetic_eo.py -- the D0 replay harness. Indoor demo, no water.

WHY THIS FILE EXISTS
04_demo/DEMO_INDOOR.md: there is no water access, so no camera can observe a vessel.
Every module downstream of the camera (association, consistency, verdict, prioritizer,
evidence) is a pure function of EoContact + AisTrack, so none of them need to change.
Only the PRODUCER of EoContact changes. This is that producer.

WHAT IT DOES
Takes the real pseudonymised DMA golden window, treats each vessel's real AIS record as
GROUND TRUTH ABOUT THE PHYSICAL HULL, and answers: "if a camera had stood at this pose,
what would it have seen?" Then it deliberately breaks some of the claims, so there is
something to find.

THE SEMANTICS THAT MAKE THIS HONEST, AND NOT CIRCULAR
    truth        = the real AIS record. The physical vessel.
    observation  = truth, projected through the camera, PLUS measurement error.
    claim        = truth, sometimes MUTATED (that mutation is the lie) or DELETED.

A spoofer is generated by changing the CLAIM and leaving the OBSERVATION at truth --
which is exactly what a real spoofer does. It lies about what it is, not about where it
is, so it still associates perfectly and can only be caught by comparing content.

THE THING THAT WOULD MAKE THIS WORTHLESS, AND HOW IT IS AVOIDED
If observations were a perfect projection of the claims, every association would score
at zero sigma, every tolerance would pass, and the demo would prove nothing except that
a == a. Worse, it would hide real defects in association.py until the judges found them.
So MEASUREMENT ERROR IS MANDATORY here, not optional: bearing noise from the pose,
fractional range error because monocular range is genuinely bad, length error, class
confusion between visually similar types, missed detections, and clutter contacts that
belong to nothing. Set --noise none only to debug the plumbing, never for a demo.

GROUND TRUTH IS WRITTEN TO A SEPARATE FILE, DELIBERATELY
No field on EoContact or AisTrack records that a vessel was tampered with. If the answer
key travelled inside the data, a downstream lane could read it by accident and score
100%, and nobody would notice until the demo. ground_truth.jsonl is the answer key and
nothing in 03_src may import it.

WHAT THIS FILE MUST NEVER DO
Import consistency.py, verdict.py or prioritizer.py. It produces INPUTS. If it ever
learns what a verdict is, it can be tuned -- consciously or not -- to produce the
verdicts we want, and the measured false-positive rate becomes a fiction.

USAGE
    python 04_demo/make_synthetic_eo.py \
        --ais 02_data/golden/fehmarn_2026-08-25_1000-1100_anon.csv \
        --out 04_demo/out/scene01 \
        --scene-time 2026-08-25T10:30:00+00:00 \
        --seed 20260830

    python 04_demo/make_synthetic_eo.py --ais <csv> --out <dir> --dry-run
"""

