def build_scene(
    *, tracks: list[AisTrack], pose: ScenePose, scene_time: datetime,
    rng: np.random.Generator, noise: NoiseModel, plan: dict[str, int],
    keep_size_consistent: bool,
) -> dict[str, Any]:
    proj = project(tracks, pose)
    visible_idx = [i for i, v in enumerate(proj["visible"]) if v]
    hidden_idx = [i for i, v in enumerate(proj["visible"]) if not v]

    if not visible_idx:
        raise SystemExit(
            "No vessel is inside the camera field of view. The pose and the traffic "
            "disagree. Re-run with --auto-pose, or widen --hfov / --max-range."
        )

    # Choose victims WITHOUT replacement so one vessel never carries two faults --
    # a hull that is both dark and spoofed is not a scenario, it is a bug generator.
    rng.shuffle(visible_idx)
    rng.shuffle(hidden_idx)
    vis_pool, hid_pool = list(visible_idx), list(hidden_idx)
    assigned: dict[int, str] = {}
    injections: list[Injection] = []

    def take(pool: list[int], kind: str) -> int | None:
        while pool:
            i = pool.pop()
            if i not in assigned:
                assigned[i] = kind
                return i
        return None

    for kind in ("dark", "length_spoof", "class_spoof", "position_spoof",
                 "heading_spoof", "missed_detection"):
        for _ in range(plan.get(kind, 0)):
            i = take(vis_pool, kind)
            if i is None:
                print(f"WARNING: not enough visible vessels for another {kind}",
                      file=sys.stderr)
                break
    for _ in range(plan.get("coverage_hole", 0)):
        i = take(hid_pool, "coverage_hole")
        if i is None:
            print("WARNING: no out-of-view vessel available for a coverage_hole "
                  "control. The false-positive measurement is weaker without it.",
                  file=sys.stderr)
            break

    out_tracks: list[AisTrack] = []
    out_contacts: list[EoContact] = []

    for i, track in enumerate(tracks):
        kind = assigned.get(i)
        visible = bool(proj["visible"][i])
        bearing = float(proj["bearing"][i])
        range_m = float(proj["range"][i])
        cid = f"c-{i:04d}"
        n_frames = int(rng.integers(3, 30))

        emit_contact = visible
        emit_track = True
        mutated = track
        detail: dict[str, Any] = {}

        if kind == "dark":
            emit_track = False
        elif kind == "missed_detection":
            emit_contact = False
        elif kind == "coverage_hole":
            emit_track = False
        elif kind == "length_spoof":
            factor = float(rng.choice([0.25, 0.3, 3.5, 5.0]))
            mutated = spoof_length(track, factor,
                                   keep_size_consistent=keep_size_consistent)
            detail = {"factor": factor,
                      "claimed_length_m_before": track.claimed_length_m,
                      "claimed_length_m_after": mutated.claimed_length_m,
                      "size_fields_kept_consistent": keep_size_consistent}
        elif kind == "class_spoof":
            options = [c for c in ("cargo", "tanker", "fishing", "passenger", "tug")
                       if c != track.claimed_ship_type]
            new_class = str(rng.choice(options))
            mutated = spoof_class(track, new_class)
            detail = {"claimed_ship_type_before": track.claimed_ship_type,
                      "claimed_ship_type_after": new_class}
        elif kind == "position_spoof":
            offset = float(rng.uniform(600.0, 1500.0))
            az = float(rng.uniform(0.0, 360.0))
            mutated = spoof_position(track, offset, az)
            detail = {"offset_m": round(offset, 1), "azimuth_deg": round(az, 1)}
        elif kind == "heading_spoof":
            delta = float(rng.choice([-140.0, -110.0, 110.0, 140.0]))
            mutated = spoof_heading(track, delta)
            detail = {"delta_deg": delta}

        # Untargeted missed detections, on top of the deliberate one.
        if emit_contact and kind is None and rng.random() < noise.p_missed_detection:
            emit_contact = False
            detail = {"reason": "random missed detection from the noise model"}
            kind_for_gt = None
        else:
            kind_for_gt = kind

        if emit_track:
            out_tracks.append(mutated)
        if emit_contact:
            out_contacts.append(make_contact(
                track=track, bearing_true=bearing, range_m=range_m, pose=pose,
                scene_time=scene_time, rng=rng, noise=noise, contact_id=cid,
                track_length_frames=n_frames))

        if kind_for_gt:
            label, subtype, must_not = EXPECTATIONS[kind_for_gt]
            injections.append(Injection(
                kind=kind_for_gt, mmsi=track.claimed_mmsi,
                track_id=mutated.track_id if emit_track else None,
                contact_id=cid if emit_contact else None,
                detail=detail, expected_label=label,
                expected_spoof_subtype=subtype, must_not_fire=must_not))

    for k in range(noise.n_clutter_contacts):
        cid = f"clutter-{k:03d}"
        out_contacts.append(make_clutter_contact(
            pose=pose, scene_time=scene_time, rng=rng, noise=noise, contact_id=cid))
        injections.append(Injection(
            kind="clutter", mmsi="-", contact_id=cid,
            detail={"note": "no vessel exists here"},
            expected_label="UNKNOWN", must_not_fire=True))

    return {"tracks": out_tracks, "contacts": out_contacts,
            "injections": injections, "projection": proj,
            "n_visible": len(visible_idx), "n_hidden": len(hidden_idx)}


