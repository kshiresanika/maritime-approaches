def write_scene(out_dir: Path, scene: dict[str, Any], manifest: dict[str, Any]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)

    def dump(name: str, rows: Iterable[Any]) -> int:
        p = out_dir / name
        n = 0
        with p.open("w", encoding="utf-8") as fh:
            for r in rows:
                obj = r.model_dump(mode="json") if hasattr(r, "model_dump") else r
                fh.write(json.dumps(obj, ensure_ascii=False) + "\n")
                n += 1
        return n

    n_t = dump("ais_tracks.jsonl", scene["tracks"])
    n_c = dump("eo_contacts.jsonl", scene["contacts"])
    n_g = dump("ground_truth.jsonl", [i.to_dict() for i in scene["injections"]])

    manifest["counts"] = {"ais_tracks": n_t, "eo_contacts": n_c,
                          "injections": n_g}
    (out_dir / "scene_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")

    # A deliberate tripwire. If this file is ever missing, someone has copied the
    # scene somewhere and dropped the caveat with it.
    (out_dir / "READ_ME_FIRST.txt").write_text(
        "SYNTHETIC ELECTRO-OPTICAL DATA. NOT A CAMERA.\n\n"
        "The AIS in this scene is real Danish Maritime Authority traffic, pseudonymised.\n"
        "The EO contacts were forward-projected from that AIS through a declared camera\n"
        "pose and perturbed with a measurement-error model. No camera observed anything.\n"
        "Anomalies were injected deliberately; ground_truth.jsonl is the answer key.\n\n"
        "Any figure derived from this scene -- detection rate, false-positive rate,\n"
        "confidence -- describes the pipeline against a MODEL of a camera, never against\n"
        "the sea. Say so on the slide.\n", encoding="utf-8")


def print_summary(scene: dict[str, Any], pose: ScenePose, manifest: dict[str, Any]) -> None:
    """Self-interpreting output: every line says what it means, so it can be pasted
    into STATUS.md without a second round trip."""
    print()
    print("=" * 74)
    print("SYNTHETIC SCENE BUILT -- D0 replay harness")
    print("=" * 74)
    print(f"pose            : {pose.pose_ref}")
    print(f"  camera at     : {pose.lat_deg:.5f} N, {pose.lon_deg:.5f} E")
    print(f"  boresight     : {pose.boresight_deg_true:.2f} deg TRUE, "
          f"HFOV {pose.hfov_deg:.1f} deg, max range {pose.max_range_m/1000:.1f} km")
    print(f"  yaw sigma     : {pose.yaw_uncertainty_deg:.2f} deg  <- floors every "
          f"bearing uncertainty in the run")
    print(f"vessels loaded  : {manifest['ais']['vessels']}")
    print(f"  in view       : {scene['n_visible']}   out of view: {scene['n_hidden']}")
    print(f"emitted         : {len(scene['tracks'])} AisTrack, "
          f"{len(scene['contacts'])} EoContact")
    print()
    print("INJECTED (ground_truth.jsonl is the answer key):")
    by_kind: dict[str, int] = {}
    for inj in scene["injections"]:
        by_kind[inj.kind] = by_kind.get(inj.kind, 0) + 1
    for kind in sorted(by_kind):
        exp = EXPECTATIONS.get(kind, ("UNKNOWN", None, True))
        flag = "  MUST NOT FIRE -- false-positive control" if exp[2] else ""
        print(f"  {kind:<18} x{by_kind[kind]:<3} expect {exp[0]:<8}{flag}")
    print()
    print("The two controls are the point. Anything can raise an alert; the measured")
    print("false-positive rate comes from how often those rows stay silent.")
    print("=" * 74)


