def auto_pose(tracks: list[AisTrack], *, max_range_m: float, hfov_deg: float,
              yaw_uncertainty_deg: float, image_width_px: int,
              image_height_px: int) -> ScenePose:
    """
    Put the camera where it sees the most traffic.

    Method: take the median vessel position as the scene centre, step back
    max_range_m * 0.8 from it along the axis of least traffic spread (so the camera
    looks ACROSS the shipping lane rather than down it -- a camera looking down a lane
    sees a queue of overlapping hulls, which is the worst case for association and a
    terrible thing to demo), and aim the boresight at the median.
    """
    lats = np.array([t.claimed_lat_deg for t in tracks])
    lons = np.array([t.claimed_lon_deg for t in tracks])
    c_lat, c_lon = float(np.median(lats)), float(np.median(lons))

    # Principal axis of the traffic, via the covariance of local metric offsets.
    m_per_deg_lat = 111_320.0
    m_per_deg_lon = 111_320.0 * math.cos(math.radians(c_lat))
    x = (lons - c_lon) * m_per_deg_lon
    y = (lats - c_lat) * m_per_deg_lat
    if len(x) >= 2 and (x.std() > 0 or y.std() > 0):
        cov = np.cov(np.vstack([x, y]))
        vals, vecs = np.linalg.eigh(cov)
        major = vecs[:, int(np.argmax(vals))]
        lane_deg = wrap_360(math.degrees(math.atan2(major[0], major[1])))
    else:
        lane_deg = 0.0

    stand_off_az = wrap_360(lane_deg + 90.0)          # perpendicular to the lane
    stand_off_m = max_range_m * 0.8
    cam_lon, cam_lat, _ = GEOD.fwd(c_lon, c_lat, stand_off_az, stand_off_m)
    boresight, _, _ = GEOD.inv(cam_lon, cam_lat, c_lon, c_lat)

    return ScenePose(
        pose_ref=f"synthetic-auto-{wrap_360(boresight):06.2f}T",
        lat_deg=float(cam_lat), lon_deg=float(cam_lon),
        boresight_deg_true=wrap_360(float(boresight)),
        hfov_deg=hfov_deg, yaw_uncertainty_deg=yaw_uncertainty_deg,
        max_range_m=max_range_m, image_width_px=image_width_px,
        image_height_px=image_height_px, height_m=25.0,
    )


