def load_truth_states(
    csv_path: Path, scene_time: datetime, window_s: float
) -> tuple[list[AisTrack], dict[str, Any]]:
    """
    One AisTrack per vessel: the report closest in time to scene_time.

    WHY NEAREST-IN-TIME AND NOT THE LATEST BEFORE: this is the TRUTH state of the hull,
    not what an operator would have had. Taking the nearest report minimises the
    dead-reckoning error baked into the scene, so any residual that association.py
    reports comes from the noise model and the injected faults -- things we chose --
    rather than from an arbitrary sampling lag we did not intend and cannot account for.
    """
    lo = scene_time - timedelta(seconds=window_s)
    hi = scene_time + timedelta(seconds=window_s)
    source = DmaCsvSource(csv_path, start_utc=lo, end_utc=hi)

    best: dict[str, tuple[float, AisTrack]] = {}
    n_read = 0
    for track in source.tracks():
        n_read += 1
        dt = abs((track.report_time_utc - scene_time).total_seconds())
        prev = best.get(track.claimed_mmsi)
        if prev is None or dt < prev[0]:
            best[track.claimed_mmsi] = (dt, track)

    tracks = [t for _, t in sorted(best.values(), key=lambda p: p[1].claimed_mmsi)]
    stats = {
        "rows_considered": n_read,
        "vessels": len(tracks),
        "window_s": window_s,
        "scene_time_utc": scene_time.isoformat(),
    }
    return tracks, stats


def assert_pseudonymised(tracks: Iterable[AisTrack], *, allow_real: bool) -> None:
    """
    Refuse to build a scene from real identities unless explicitly forced.

    WHY THIS IS A HARD STOP AND NOT A WARNING: constraint 2 -- a demo that labels a real
    named vessel as a spoofer is defamatory and indefensible, and the DMA licence
    separately forbids combining this data with others to identify individuals. The
    golden-window pseudonymiser puts every synthetic MMSI on the 999 prefix, which is a
    MID unassigned to any country, so it is recognisably fake to anyone who checks.
    A run that finds non-999 MMSIs is reading the wrong file -- almost certainly the
    *_real* one sitting next to it -- and that is exactly the mistake worth stopping.
    """
    real = sorted({t.claimed_mmsi for t in tracks if not t.claimed_mmsi.startswith("999")})
    if not real:
        return
    msg = (
        f"{len(real)} of the loaded MMSIs are not 999-prefixed, i.e. they are REAL "
        f"vessel identities (first few: {real[:5]}). Point --ais at the *_anon.csv "
        f"produced by 02_data/make_golden_window.py."
    )
    if not allow_real:
        raise SystemExit("REFUSING TO BUILD SCENE: " + msg)
    print("WARNING -- --allow-real-identities was passed. " + msg, file=sys.stderr)
    print("WARNING -- output of this run must NEVER be committed or shown publicly.",
          file=sys.stderr)


